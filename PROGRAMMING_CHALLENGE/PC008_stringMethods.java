package PROGRAMMING_CHALLENGE;

public class PC008_stringMethods {

    public static void main(String[] args) {


        String string = "HelloWorld";

        System.out.println("\n" + string + " string.length();: " + string.length());

        System.out.println("\n" + string + " string.toUpperCase();: " + string.toUpperCase());

        System.out.println("\n" + string + " string.toLowerCase();: " + string.toLowerCase());

        System.out.println("\n" + string + " string.charAt(0);: " + string.charAt(0));

        System.out.println("\n" + string + " string.charAt(9);: " + string.charAt(9));

        System.out.println("\n" + string + " string.charAt(9);: " + string.substring(1, 5));








}}
